"use client";

import React, { useState, useEffect, useTransition, useMemo } from "react";
import { X, Calendar, Briefcase, Layers, RefreshCw, AlertCircle, MapPin, Link2, Info } from "lucide-react";
import Swal from "sweetalert2";
import type { Department, JobLevel, JobPosition, KpiPeriod, Pit, DepartmentMapping } from "@/db/schema";

export interface TemplateModalProps {
  isOpen: boolean;
  onClose: () => void;
  departments: Department[];
  jobLevels: JobLevel[];
  positions?: JobPosition[];
  periods?: KpiPeriod[];
  pits?: Pit[];
  sites?: { id: number; code: string; name: string }[];
  departmentMappings?: DepartmentMapping[];
  existingTemplates?: { id: number; departmentId: number; jobLevelId: number; name: string }[];
  action: (fd: FormData) => Promise<void>;
}

export function TemplateModal({
  isOpen,
  onClose,
  departments,
  jobLevels,
  positions: initialPositions,
  periods: initialPeriods,
  pits: initialPits,
  sites: initialSites,
  departmentMappings = [],
  existingTemplates = [],
  action,
}: TemplateModalProps) {
  const [site, setSite] = useState("");
  const [departmentId, setDepartmentId] = useState(String(departments[0]?.id ?? ""));
  const [pitId, setPitId] = useState("");
  const [jobLevelId, setJobLevelId] = useState(String(jobLevels[0]?.id ?? ""));
  const [jobPositionId, setJobPositionId] = useState("");
  const [periodId, setPeriodId] = useState("");
  const [effectiveDate, setEffectiveDate] = useState(() => new Date().toISOString().split("T")[0]);
  const [description, setDescription] = useState("");

  // Dynamic positions, periods, pits & sites if not passed as props
  const [positionsList, setPositionsList] = useState<JobPosition[]>(initialPositions || []);
  const [periodsList, setPeriodsList] = useState<KpiPeriod[]>(initialPeriods || []);
  const [pitsList, setPitsList] = useState<Pit[]>(initialPits || []);
  const [sitesList, setSitesList] = useState<{ id: number; code: string; name: string }[]>(
    initialSites || []
  );
  const [isLoadingLookups, setIsLoadingLookups] = useState(false);
  const [lookupError, setLookupError] = useState<string | null>(null);

  // Sync sites if passed via props or fetch from database API
  useEffect(() => {
    if (initialSites && initialSites.length > 0) {
      setSitesList(initialSites);
    } else if (isOpen) {
      fetch("/api/admin/sites")
        .then((res) => {
          if (!res.ok) return null;
          return res.json();
        })
        .then((data) => {
          if (data?.sites) setSitesList(data.sites);
        })
        .catch(() => {});
    }
  }, [isOpen, initialSites]);

  // Sync pits if passed via props or fetch if missing
  useEffect(() => {
    if (initialPits && initialPits.length > 0) {
      setPitsList(initialPits);
    } else if (isOpen) {
      fetch("/api/admin/pits")
        .then((res) => {
          if (!res.ok) return null;
          return res.json();
        })
        .then((data) => {
          if (data?.pits) setPitsList(data.pits);
        })
        .catch(() => {});
    }
  }, [isOpen, initialPits]);

  // Filter PIT by selected Site
  const availablePits = useMemo(() => {
    const activePits = pitsList.filter((p) => p.isActive);
    if (!site || site === "ALL") return activePits;
    return activePits.filter((p) => p.site === site);
  }, [pitsList, site]);

  // Selected entities for auto naming & references
  const selectedDept = useMemo(
    () => departments.find((d) => String(d.id) === String(departmentId)),
    [departments, departmentId]
  );

  const selectedPit = useMemo(
    () => pitsList.find((p) => String(p.id) === String(pitId)),
    [pitsList, pitId]
  );

  const selectedLvl = useMemo(
    () => jobLevels.find((l) => String(l.id) === String(jobLevelId)),
    [jobLevels, jobLevelId]
  );

  const selectedPer = useMemo(
    () => periodsList.find((p) => String(p.id) === String(periodId)),
    [periodsList, periodId]
  );

  // Detect matching Department Mappings for reference
  const matchedMappings = useMemo(() => {
    if (!departmentMappings || departmentMappings.length === 0 || !departmentId) return [];
    const deptNum = Number(departmentId);
    return departmentMappings.filter((m) => {
      if (m.departmentId !== deptNum) return false;
      if (site && site !== "ALL" && m.site && m.site !== site) return false;
      if (pitId && pitId !== "ALL" && m.pitId && String(m.pitId) !== String(pitId)) return false;
      return true;
    });
  }, [departmentMappings, departmentId, site, pitId]);

  // Auto-generate Template Name based on Departemen + PIT + Job Level + Periode KPI
  const autoGeneratedName = useMemo(() => {
    const deptName = selectedDept?.name?.trim() || "";
    const pitName = selectedPit?.name?.trim() || "";
    const lvlName = selectedLvl?.name?.trim() || "";
    const yearStr = selectedPer?.year
      ? String(selectedPer.year).trim()
      : new Date().getFullYear().toString();

    if (!deptName && !lvlName) return "";
    const pitPart = pitName ? ` - ${pitName}` : "";
    return `Template KPI ${deptName || "-"}${pitPart} - ${lvlName || "-"} - ${yearStr}`;
  }, [selectedDept, selectedPit, selectedLvl, selectedPer]);

  const [isPending, startTransition] = useTransition();

  // Fetch lookups if not provided via props
  useEffect(() => {
    if (!isOpen) return;

    if (!initialPositions || initialPositions.length === 0 || !initialPeriods || initialPeriods.length === 0) {
      setIsLoadingLookups(true);
      setLookupError(null);
      fetch("/api/admin/job-positions")
        .then((res) => {
          if (!res.ok) throw new Error("Gagal memuat master jabatan dan periode.");
          return res.json();
        })
        .then((data) => {
          if (data.positions && (!initialPositions || initialPositions.length === 0)) {
            setPositionsList(data.positions);
          }
          if (data.periods && (!initialPeriods || initialPeriods.length === 0)) {
            setPeriodsList(data.periods);
            const active = data.periods.find((p: KpiPeriod) => p.status === "ACTIVE");
            if (active) {
              setPeriodId(String(active.id));
              if (active.startDate) {
                setEffectiveDate(String(active.startDate));
              }
            } else if (data.periods[0]) {
              setPeriodId(String(data.periods[0].id));
            }
          }
        })
        .catch((err: unknown) => {
          const msg = err instanceof Error ? err.message : "Gagal memuat data referensi.";
          setLookupError(msg);
        })
        .finally(() => {
          setIsLoadingLookups(false);
        });
    } else {
      if (initialPositions) setPositionsList(initialPositions);
      if (initialPeriods) {
        setPeriodsList(initialPeriods);
        const active = initialPeriods.find((p) => p.status === "ACTIVE");
        if (active) {
          setPeriodId(String(active.id));
          if (active.startDate) {
            setEffectiveDate(String(active.startDate));
          }
        } else if (initialPeriods[0]) {
          setPeriodId(String(initialPeriods[0].id));
        }
      }
    }
  }, [isOpen, initialPositions, initialPeriods]);

  // Reset form when opened
  useEffect(() => {
    if (isOpen) {
      const initialDept = String(departments[0]?.id ?? "");
      setSite("");
      setPitId("");
      setDepartmentId(initialDept);
      setJobLevelId(String(jobLevels[0]?.id ?? ""));
      setJobPositionId("");
      setDescription("");

      const activePer = periodsList.find((p) => p.status === "ACTIVE") || periodsList[0];
      if (activePer) {
        setPeriodId(String(activePer.id));
        if (activePer.startDate) {
          setEffectiveDate(String(activePer.startDate));
        } else {
          setEffectiveDate(new Date().toISOString().split("T")[0]);
        }
      } else {
        setEffectiveDate(new Date().toISOString().split("T")[0]);
      }
    }
  }, [isOpen, departments, jobLevels, periodsList]);

  // Handle ESC key to close modal
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape" && isOpen && !isPending) {
        onClose();
      }
    };
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [isOpen, onClose, isPending]);

  // Filter positions by selected department
  const filteredPositions = useMemo(() => {
    if (!departmentId) return positionsList;
    const selectedDeptNum = Number(departmentId);
    const matched = positionsList.filter((p) => p.departmentId === selectedDeptNum);
    return matched.length > 0 ? matched : positionsList;
  }, [positionsList, departmentId]);

  if (!isOpen) return null;

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();

    const finalName = autoGeneratedName.trim();
    if (!finalName) {
      void Swal.fire({
        icon: "warning",
        title: "Nama Template Gagal Terbentuk",
        text: "Pastikan Departemen, Job Level, dan Periode KPI telah dipilih.",
        confirmButtonColor: "#0f172a",
      });
      return;
    }

    if (!departmentId) {
      void Swal.fire({
        icon: "warning",
        title: "Departemen Wajib Dipilih",
        text: "Silakan pilih departemen yang bersangkutan.",
        confirmButtonColor: "#0f172a",
      });
      return;
    }

    if (!jobLevelId) {
      void Swal.fire({
        icon: "warning",
        title: "Job Level Wajib Dipilih",
        text: "Silakan pilih jenjang jabatan (job level).",
        confirmButtonColor: "#0f172a",
      });
      return;
    }

    if (!periodId) {
      void Swal.fire({
        icon: "warning",
        title: "Periode KPI Wajib Dipilih",
        text: "Silakan pilih periode evaluasi KPI yang berlaku.",
        confirmButtonColor: "#0f172a",
      });
      return;
    }

    if (!effectiveDate) {
      void Swal.fire({
        icon: "warning",
        title: "Tanggal Efektif Wajib Diisi",
        text: "Silakan masukkan tanggal mulai berlakunya template KPI ini.",
        confirmButtonColor: "#0f172a",
      });
      return;
    }

    const fd = new FormData();
    fd.append("name", finalName);
    fd.append("departmentId", departmentId);
    fd.append("jobLevelId", jobLevelId);
    if (site && site !== "ALL") {
      fd.append("site", site);
      const sObj = sitesList.find((s) => s.code === site);
      if (sObj) fd.append("siteId", String(sObj.id));
    }
    if (pitId && pitId !== "" && pitId !== "ALL") fd.append("pitId", pitId);
    if (matchedMappings[0]) fd.append("departmentMappingId", String(matchedMappings[0].id));
    if (jobPositionId) fd.append("jobPositionId", jobPositionId);
    fd.append("periodId", periodId);
    fd.append("effectiveDate", effectiveDate);
    if (description.trim()) fd.append("description", description.trim());
    fd.append("totalWeight", "1.15"); // 115% standard total weight

    startTransition(async () => {
      try {
        await action(fd);
        onClose();
      } catch (err: unknown) {
        if (
          err &&
          typeof err === "object" &&
          "digest" in err &&
          String((err as { digest?: unknown }).digest).startsWith("NEXT_REDIRECT")
        ) {
          onClose();
          throw err;
        }
        const msg = err instanceof Error ? err.message : "Gagal membuat template KPI.";
        void Swal.fire({
          icon: "error",
          title: "Gagal Membuat Template",
          text: msg,
          confirmButtonColor: "#0f172a",
        });
      }
    });
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-5 bg-slate-900/60 backdrop-blur-xs animate-in fade-in duration-200"
      onClick={() => {
        if (!isPending) onClose();
      }}
      role="dialog"
      aria-modal="true"
      aria-labelledby="template-modal-title"
    >
      <div
        className="bg-white rounded-2xl shadow-2xl border border-slate-200 w-full max-w-2xl max-h-[90vh] overflow-hidden flex flex-col animate-in zoom-in-95 duration-150"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between bg-white shrink-0">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-blue-50 text-blue-600 border border-blue-100 flex items-center justify-center shrink-0">
              <Layers className="w-5 h-5" />
            </div>
            <div>
              <h3 id="template-modal-title" className="text-base font-bold text-slate-900">
                Buat Template KPI
              </h3>
              <p className="text-xs text-slate-500 mt-0.5">
                Lengkapi informasi template sebelum membuat struktur KPI.
              </p>
            </div>
          </div>
          <button
            type="button"
            onClick={onClose}
            disabled={isPending}
            aria-label="Tutup modal"
            title="Tutup (Esc)"
            className="p-2 text-slate-400 hover:text-slate-700 hover:bg-slate-100 rounded-xl transition cursor-pointer disabled:opacity-50 focus:outline-none focus:ring-2 focus:ring-blue-500"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Form with scrollable body and fixed footer */}
        <form onSubmit={handleSubmit} className="flex flex-col flex-1 min-h-0 overflow-hidden">
          {/* Scrollable Body */}
          <div className="p-6 space-y-4 overflow-y-auto flex-1">
            {lookupError && (
              <div className="flex items-center gap-2 rounded-xl border border-rose-200 bg-rose-50 p-2.5 text-xs text-rose-700">
                <AlertCircle className="h-4 w-4 shrink-0 text-rose-500" />
                <span>{lookupError}</span>
              </div>
            )}

            {/* Info Pemisahan Data (Site, Departemen, PIT) */}
            <div className="rounded-xl border border-slate-200 bg-slate-50/70 p-3 text-[11px] text-slate-600 flex items-start gap-2.5">
              <Layers className="w-4 h-4 text-blue-600 shrink-0 mt-0.5" />
              <div>
                <div className="font-bold text-slate-800">
                  Pemisahan 3 Kategori Data Terstruktur:
                </div>
                <div className="text-slate-500 mt-0.5 leading-relaxed">
                  <span className="font-semibold text-slate-700">Site</span> (Unit Kerja Operasional),{" "}
                  <span className="font-semibold text-slate-700">Departemen</span> (Organisasi Standar), dan{" "}
                  <span className="font-semibold text-slate-700">PIT</span> (Work Location penambangan).
                </div>
              </div>
            </div>

            {/* Site & PIT (Opsional) */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  Site Operasional <span className="text-slate-400 font-normal">(Opsional)</span>
                </label>
                <select
                  value={site}
                  onChange={(e) => {
                    const val = e.target.value;
                    setSite(val);
                    if (val && pitId) {
                      const currPit = pitsList.find((p) => String(p.id) === String(pitId));
                      if (currPit && currPit.site !== val) {
                        setPitId("");
                      }
                    }
                  }}
                  className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl bg-white text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition cursor-pointer"
                >
                  <option value="">-- Semua Site (Universal) --</option>
                  {sitesList.map((s) => (
                    <option key={s.id} value={s.code}>
                      {s.name} ({s.code})
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  PIT Lapangan <span className="text-slate-400 font-normal">(Opsional)</span>
                </label>
                <select
                  value={pitId}
                  onChange={(e) => setPitId(e.target.value)}
                  className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl bg-white text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition cursor-pointer"
                >
                  <option value="">-- Tanpa PIT (Semua PIT / Non-PIT) --</option>
                  {availablePits.map((p) => (
                    <option key={p.id} value={p.id}>
                      {p.code ? `[${p.code}] ` : ""}{p.name} ({p.site})
                    </option>
                  ))}
                </select>
                <p className="text-[10px] text-slate-400 mt-1">
                  Pilih jika template khusus untuk pit tertentu. Kosongkan untuk departemen non-PIT.
                </p>
              </div>
            </div>

            {/* 1. Departemen & Job Level */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  Departemen <span className="text-rose-500">*</span>
                </label>
                <select
                  required
                  value={departmentId}
                  onChange={(e) => setDepartmentId(e.target.value)}
                  className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl bg-white text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition cursor-pointer"
                >
                  {departments.map((d) => (
                    <option key={d.id} value={d.id}>
                      {d.name} ({d.code})
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  Job Level <span className="text-rose-500">*</span>
                </label>
                <select
                  required
                  value={jobLevelId}
                  onChange={(e) => setJobLevelId(e.target.value)}
                  className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl bg-white text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition cursor-pointer"
                >
                  {jobLevels.map((l) => (
                    <option key={l.id} value={l.id}>
                      {l.name} ({l.code})
                    </option>
                  ))}
                </select>
              </div>
            </div>

            {/* Referensi Mapping Departemen Terdeteksi */}
            {matchedMappings.length > 0 && (
              <div className="rounded-xl border border-blue-200 bg-blue-50/70 p-3 space-y-1.5 text-xs">
                <div className="flex items-center gap-1.5 font-bold text-blue-900">
                  <Link2 className="w-3.5 h-3.5 text-blue-600 shrink-0" />
                  <span>Referensi Mapping Departemen Terdeteksi ({matchedMappings.length})</span>
                </div>
                <p className="text-[11px] text-slate-600">
                  Template ini otomatis terhubung sebagai referensi untuk aturan mapping import berikut:
                </p>
                <div className="flex flex-wrap gap-1 max-h-20 overflow-y-auto">
                  {matchedMappings.slice(0, 5).map((m) => {
                    const mPit = m.pitId ? pitsList.find((p) => p.id === m.pitId) : null;
                    return (
                      <span
                        key={m.id}
                        className="inline-flex items-center gap-1 px-2 py-0.5 rounded-md bg-white border border-blue-200 text-[11px] font-mono text-blue-800"
                      >
                        <span>{m.rawDepartmentName}</span>
                        {mPit && (
                          <span className="text-[10px] text-amber-700 font-sans font-semibold">
                            ({mPit.name})
                          </span>
                        )}
                      </span>
                    );
                  })}
                  {matchedMappings.length > 5 && (
                    <span className="text-[11px] text-slate-500 self-center">
                      +{matchedMappings.length - 5} lainnya
                    </span>
                  )}
                </div>
              </div>
            )}

            {/* 2. Periode KPI & Effective Date */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  Periode KPI <span className="text-rose-500">*</span>
                </label>
                {isLoadingLookups ? (
                  <div className="flex items-center gap-2 px-3 py-2 text-xs border border-slate-200 rounded-xl bg-slate-50 text-slate-500">
                    <RefreshCw className="h-3.5 w-3.5 animate-spin" />
                    <span>Memuat daftar periode aktif...</span>
                  </div>
                ) : (
                  <select
                    required
                    value={periodId}
                    onChange={(e) => setPeriodId(e.target.value)}
                    className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl bg-white text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition cursor-pointer"
                  >
                    {periodsList.length === 0 ? (
                      <option value="" disabled>
                        Tidak ada periode aktif tersedia
                      </option>
                    ) : (
                      periodsList.map((p) => (
                        <option key={p.id} value={p.id}>
                          {p.name} ({p.year}) {p.status === "ACTIVE" ? "[Aktif]" : ""}
                        </option>
                      ))
                    )}
                  </select>
                )}
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  Effective Date <span className="text-rose-500">*</span>
                </label>
                <input
                  type="date"
                  required
                  value={effectiveDate}
                  onChange={(e) => setEffectiveDate(e.target.value)}
                  className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl bg-white text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition"
                />
              </div>
            </div>

            {/* 3. Nama Template (Otomatis & Tidak Dapat Diedit Manual) */}
            <div className="rounded-xl border border-blue-200 bg-blue-50/50 p-3.5 space-y-1.5">
              <div className="flex items-center justify-between">
                <label className="text-xs font-bold text-slate-800 flex items-center gap-1.5">
                  <span>Nama Template</span>
                  <span className="px-1.5 py-0.5 rounded text-[10px] font-semibold bg-blue-600 text-white">
                    Otomatis
                  </span>
                </label>
                <span className="text-[10px] text-slate-500 font-medium">
                  Template KPI [Dept] - [PIT] - [Level] - [Tahun]
                </span>
              </div>
              <div className="relative">
                <input
                  type="text"
                  readOnly
                  tabIndex={-1}
                  value={autoGeneratedName}
                  placeholder="Template KPI [Departemen] - [PIT] - [Job Level] - [Tahun]"
                  className="w-full px-3 py-2.5 text-xs border border-blue-200 rounded-lg bg-white text-slate-900 font-bold select-all focus:outline-none shadow-2xs cursor-not-allowed"
                />
              </div>
              <p className="text-[11px] text-slate-500">
                Nama template dibuat otomatis dan diperbarui setiap kali Departemen, PIT, Job Level, atau Periode KPI berubah.
              </p>
            </div>

            {/* 4. Position/Jabatan (Opsional) & 5. Deskripsi (Opsional) */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  Jabatan / Position <span className="text-slate-400 font-normal">(Opsional)</span>
                </label>
                <select
                  value={jobPositionId}
                  onChange={(e) => setJobPositionId(e.target.value)}
                  className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl bg-white text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition cursor-pointer"
                >
                  <option value="">-- Berlaku Umum (Semua Jabatan) --</option>
                  {filteredPositions.map((p) => (
                    <option key={p.id} value={p.id}>
                      {p.name}
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">
                  Deskripsi <span className="text-slate-400 font-normal">(Opsional)</span>
                </label>
                <textarea
                  rows={2}
                  value={description}
                  onChange={(e) => setDescription(e.target.value)}
                  placeholder="Jelaskan tujuan dan ruang lingkup template ini..."
                  className="w-full px-3 py-2 text-xs border border-slate-200 rounded-xl text-slate-800 focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 transition resize-none"
                />
              </div>
            </div>
          </div>

          {/* Modal Footer - Fixed at bottom */}
          <div className="px-6 py-3.5 bg-slate-50 border-t border-slate-100 flex items-center justify-end gap-2.5 shrink-0">
            <button
              type="button"
              onClick={onClose}
              disabled={isPending}
              className="px-4 py-2 text-xs font-semibold text-slate-700 hover:text-slate-900 bg-white hover:bg-slate-100 border border-slate-200 rounded-xl transition cursor-pointer disabled:opacity-50 focus:outline-none focus:ring-2 focus:ring-slate-400"
            >
              Batal
            </button>
            <button
              type="submit"
              disabled={isPending || isLoadingLookups}
              className="inline-flex items-center gap-1.5 px-5 py-2 text-xs font-semibold text-white bg-blue-600 hover:bg-blue-700 rounded-xl shadow-xs transition cursor-pointer disabled:opacity-50 focus:outline-none focus:ring-2 focus:ring-blue-500 focus:ring-offset-1"
            >
              {isPending ? (
                <>
                  <RefreshCw className="h-3.5 w-3.5 animate-spin" />
                  <span>Membuat...</span>
                </>
              ) : (
                <span>Buat Template</span>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
